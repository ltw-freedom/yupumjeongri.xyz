/** '40만 ~ 90만원' → '40만~90만원' (문장 안 표기) */
const inline = (range: string) => range.replace(/\s*~\s*/g, '~');
const base = (key: PriceRow['key']) => inline(priceRow(key).range);

/** 단가표 행을 이름으로 찾는다. 이름이 바뀌면 조용히 빈 금액이 나가지 않게 빌드를 멈춘다. */
function rate(item: string): string {
  const row = unitRates.find((u) => u.item === item);
  if (!row) throw new Error(`process.ts: pricing.ts unitRates 에 '${item}' 행이 없습니다`);
  return inline(row.rate);
}

/** 공통 FAQ(faqs.ts)의 답을 그대로 빌려 온다 — 같은 질문에 두 가지 답이 생기지 않게 */
function faqAnswer(q: string): string {
  const item = allFaqItems.find((f) => f.q === q);
  if (!item) throw new Error(`process.ts: faqs.ts 에 '${q}' 문답이 없습니다`);
  return item.a;
}

