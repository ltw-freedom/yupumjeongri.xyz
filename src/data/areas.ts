/** 전 지역 도시 목록 (region 정보를 붙여서 반환) */
export const allCities = regions.flatMap((region) =>
  region.cities.map((city) => ({ ...city, region })),
);

export function getRegion(slug: string): Region | undefined {
  return regions.find((region) => region.slug === slug);
}

/** 같은 광역 안의 인접 지역 (내부 링크용) */
export function nearbyCities(regionSlug: string, citySlug: string, limit = 3) {
  const region = getRegion(regionSlug);
  if (!region) return [];
  return region.cities.filter((city) => city.slug !== citySlug).slice(0, limit);
}
