export type City = {
  slug: string;
  name: string;
  /** 목록/카드 및 meta description 에 쓰는 한 줄 */
  summary: string;
  /** 이 지역 현장의 실제 특징 (2~4개) */
  traits: string[];
  /** 서비스 범위 — 주요 동/생활권 */
  coverage: string[];
  /** 이 지역에서 특히 비용에 영향을 주는 요소 */
  costFactors: string[];
  /** 이 지역에서 실제로 자주 받는 질문 */
  faqs: { q: string; a: string }[];
};

