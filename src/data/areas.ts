/**
 * 지역 데이터.
 *
 * 중요: 여기에 도시를 추가하면 /area/{region}/{city}/ 페이지가 자동으로 생성된다.
 * 다만 지역명만 바꿔치기한 페이지는 만들지 않는다. City 타입의 필드가 전부
 * 필수인 이유가 그것이다 — 지역 특성 / 비용에 영향을 주는 요소 / FAQ 가
 * 실제로 그 지역에서 다르지 않다면, 그 지역 페이지는 아직 만들지 말 것.
 *
 * 지역 특징(traits)에 "요청이 많다·문의가 꾸준하다" 같은 빈도 주장을 쓰지 않는다 — 접수 기록으로
 * 실증할 수 없다(2026-10-23 정리). 통계가 필요하면 출처 있는 숫자(cityStats.ts)만 쓴다.
 * FAQ 의 금액은 pricing.ts 에서 가져온다 — 손으로 적으면 가격을 고칠 때 어긋난다.
 */

import { priceRow, unitRates, vatLabel, pricesAsOf } from './pricing';

/** '40만 ~ 90만원' → '40만~90만원' (문장 안에 넣는 표기) */
const range = (key: Parameters<typeof priceRow>[0]) => priceRow(key).range.replace(/\s*~\s*/g, '~');
const specialAdd = () => range('special').replace(/^위 금액\s*\+\s*/, '');
/** 단가표(unitRates) 한 줄 — '작업 인력' → '10만~15만원' */
const rate = (item: string) => unitRates.find((row) => row.item.startsWith(item))!.rate.replace(/\s*~\s*/g, '~');

export type City = {
  slug: string;
  name: string;
  /** 목록/카드 및 meta description 에 쓰는 한 줄 */
  summary: string;
  /** 이 지역 현장의 실제 특징 (2~4개) */
  traits: string[];
  /** 서비스 범위 — 주요 동/생활권 */
  coverage: string[];
  /** 이 지역에서 특히 비용에 영향을 주는 요소 */
  costFactors: string[];
  /** 이 지역에서 실제로 자주 받는 질문 */
  faqs: { q: string; a: string }[];
};

